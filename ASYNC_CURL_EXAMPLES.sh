# Workflow 1: Simple Start & Poll
echo "WORKFLOW 1: Start & Poll Until Complete"
echo "════════════════════════════════════════"
echo ""
echo "#!/bin/bash"
echo ""
echo "# 1. Start vectorization"
echo "echo \"Starting vectorization...\""
echo "JOB_ID=\$(curl -s -X POST \"${BASE_URL}/api/v1/vectorize-async\" | jq -r '.data.job_id')"
echo "echo \"Job ID: \$JOB_ID\""
echo ""
echo "# 2. Poll status until complete"
echo "while true; do"
echo "  STATUS=\$(curl -s -X GET \"${BASE_URL}/api/v1/vectorization-job/\$JOB_ID/status\" | jq '.data')"
echo "  JOB_STATUS=\$(echo \"\$STATUS\" | jq -r '.status')"
