echo "  printf \"Status: %-10s | Progress: %6.1f%% | Elapsed: %6.1fs\\r\" \"\$JOB_STATUS\" \"\$PROGRESS\" \"\$ELAPSED\""
echo "  "
echo "  if [ \"\$JOB_STATUS\" = \"completed\" ] || [ \"\$JOB_STATUS\" = \"failed\" ]; then"
echo "    echo \"\""
echo "    echo \"Job finished with status: \$JOB_STATUS\""
echo "    break"
echo "  fi"
echo "  "
echo "  sleep 5"
echo "done"
echo ""
echo "---"
