# Workflow 2: With Error Handling
echo "WORKFLOW 2: Start, Poll dengan Error Handling"
echo "═════════════════════════════════════════════"
echo ""
echo "#!/bin/bash"
echo ""
echo "BASE_URL=\"${BASE_URL}\""
echo "TIMEOUT=3600  # 1 hour timeout"
echo "INTERVAL=5"
echo "ELAPSED=0"
echo ""
echo "# Start"
echo "echo \"Starting vectorization...\""
echo "RESPONSE=\$(curl -s -X POST \"\$BASE_URL/api/v1/vectorize-async\")"
echo "if [ \$? -ne 0 ]; then"
echo "  echo \"Error: Failed to start vectorization\""
echo "  exit 1"
echo "fi"
echo ""
echo "JOB_ID=\$(echo \"\$RESPONSE\" | jq -r '.data.job_id')"
echo "if [ -z \"\$JOB_ID\" ] || [ \"\$JOB_ID\" = \"null\" ]; then"
echo "  echo \"Error: Failed to get job_id\""
echo "  echo \"Response: \$RESPONSE\""
echo "  exit 1"
echo "fi"
echo ""
echo "echo \"Job started: \$JOB_ID\""
echo ""
echo "# Poll"
echo "while [ \$ELAPSED -lt \$TIMEOUT ]; do"
echo "  STATUS=\$(curl -s -X GET \"\$BASE_URL/api/v1/vectorization-job/\$JOB_ID/status\" | jq '.data')"
echo "  JOB_STATUS=\$(echo \"\$STATUS\" | jq -r '.status')"
echo "  "
echo "  case \"\$JOB_STATUS\" in"
echo "    pending)"
echo "      echo \"Job pending...\""
echo "      ;;"
echo "    running)"
echo "      PROGRESS=\$(echo \"\$STATUS\" | jq '.progress.progress_percentage')"
echo "      echo \"Progress: \$PROGRESS%\""
echo "      ;;"
echo "    completed)"
echo "      echo \"Job completed!\""
echo "      echo \"\$STATUS\" | jq '.result'"
echo "      exit 0"
echo "      ;;"
echo "    failed)"
echo "      echo \"Job failed!\""
echo "      echo \"\$STATUS\" | jq '.error'"
echo "      exit 1"
echo "      ;;"
echo "  esac"
echo "  "
echo "  sleep \$INTERVAL"
echo "  ELAPSED=\$((ELAPSED + INTERVAL))"
echo "done"
echo ""
echo "echo \"Error: Job timeout after \$TIMEOUT seconds\""
echo "exit 1"
echo ""
echo "---"
echo ""

